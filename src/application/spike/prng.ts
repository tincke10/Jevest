/**
 * Small deterministic PRNG utilities shared by the spike's dry-run script
 * and stratified sampler. No cryptographic properties needed — just
 * reproducible, seedable randomness for smoke-test data and dataset
 * subsampling.
 */

/** mulberry32: small, fast, deterministic PRNG. Public domain algorithm. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** FNV-1a string hash, used to derive a per-item seed from a global seed. */
export function hashString(value: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
